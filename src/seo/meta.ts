export interface PageMeta {
  path: string;
  /** <title> text (the " | WIKA PPF" suffix is added automatically, except on the home page) */
  title: string;
  /** meta description — aim for 120–160 characters */
  description: string;
  keywords: string[];
  /** schema.org WebPage subtype for this page */
  pageType: 'WebPage' | 'AboutPage' | 'ContactPage' | 'CollectionPage' | 'ItemPage' | 'FAQPage';
  /** social share card: photo slug from media.json + a short headline and kicker */
  og: { image: string; headline: string; kicker: string };
  /** alt text describing the page's main image */
  imageAlt: string;
  type?: 'website' | 'article';
  article?: { published: string; modified: string; section: string; tags: string[] };
  noindex?: boolean;
  /** responsive image (from /public/images) to preload — speeds up the largest paint */
  preload?: { name: string; widths: number[]; sizes: string };
  breadcrumbs?: { name: string; path: string }[];
  jsonLd?: object[];
}

const BRAND_KEYWORDS = ['WIKA PPF', 'Wika paint protection film', 'Wika Germany PPF', 'paint protection film', 'PPF'];

export const abs = (p: string) => site.url + p;

type MediaEntry = { w: number; h: number; widths: number[] };
const mediaMap = media as Record<string, MediaEntry>;
/** absolute URL of the largest generated width ≤ 1300px for an image slug */
export const imgUrl = (slug: string) => {
  const m = mediaMap[slug];
  const w = m ? Math.max(...m.widths.filter((x) => x <= 1300)) : 1280;
  return abs(`/images/${slug}-${w}.webp`);
};
/** per-page social card generated by scripts/make-og.mjs */
export const ogSlug = (m: PageMeta) => (m.path === '/' ? 'home' : m.path.replace(/^\/|\/$/g, '').replace(/\//g, '--'));
export const ogUrl = (m: PageMeta) => abs(`/og/${ogSlug(m)}.jpg`);

