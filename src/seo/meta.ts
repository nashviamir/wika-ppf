export const allPages: PageMeta[] = [...staticPages, ...productPages, ...guidePages];

export function getMeta(pathname: string): PageMeta {
  const p = pathname.endsWith('/') ? pathname : pathname + '/';
  return allPages.find((m) => m.path === p) ?? notFoundMeta;
}

export function fullTitle(m: PageMeta) {
  return m.path === '/' ? m.title : `${m.title} | WIKA PPF`;
}

/** WebPage-type node for a page, merged with any page-specific extras */
function webPageLd(m: PageMeta, extras: object[]) {
  const url = abs(m.path);
  const merged = Object.assign({}, ...extras.filter((e) => !('@context' in e)));
  return {
    '@context': 'https://schema.org',
    '@type': m.pageType === 'FAQPage' ? 'WebPage' : m.pageType,
    '@id': url + '#webpage',
    url,
    name: fullTitle(m),
    description: m.description,
    inLanguage: 'en',
    isPartOf: { '@id': websiteId },
    publisher: { '@id': orgId },
    primaryImageOfPage: { '@type': 'ImageObject', url: imgUrl(m.og.image), caption: m.imageAlt },
    ...(m.breadcrumbs?.length ? { breadcrumb: { '@id': url + '#breadcrumb' } } : {}),
    ...(m.pageType === 'FAQPage' ? { mainEntity: { '@id': abs('/faq/#faq') } } : {}),
    ...merged,
  };
}

/** Builds the <head> HTML for a page (used by the prerender step). */
export function headHtml(m: PageMeta) {
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
  const url = abs(m.path === '/404/' ? '/' : m.path);
  const image = ogUrl(m);
  const title = fullTitle(m);

  const extras = m.jsonLd ?? [];
  const ld: object[] = m.noindex ? [] : [organization, website, webPageLd(m, extras)];
  ld.push(...extras.filter((e) => '@context' in e));
  if (m.breadcrumbs?.length) ld.push({ ...breadcrumbLd(m.breadcrumbs), '@id': abs(m.path) + '#breadcrumb' });

  const tags = [
    `<title>${esc(title)}</title>`,
    `<meta name="description" content="${esc(m.description)}" />`,
    m.keywords.length ? `<meta name="keywords" content="${esc([...new Set(m.keywords)].join(', '))}" />` : '',
    `<meta name="author" content="${site.name}" />`,
    `<meta name="robots" content="${m.noindex ? 'noindex, follow' : 'index, follow, max-image-preview:large, max-snippet:-1'}" />`,
    m.noindex ? '' : `<link rel="canonical" href="${url}" />`,
    m.noindex ? '' : `<link rel="alternate" hreflang="en" href="${url}" />`,
    m.noindex ? '' : `<link rel="alternate" hreflang="x-default" href="${url}" />`,
    // Open Graph (Facebook, LinkedIn, WhatsApp, Telegram, Slack…)
    `<meta property="og:type" content="${m.type === 'article' ? 'article' : 'website'}" />`,
    `<meta property="og:site_name" content="${site.name}" />`,
    `<meta property="og:locale" content="${site.locale}" />`,
    `<meta property="og:title" content="${esc(title)}" />`,
    `<meta property="og:description" content="${esc(m.description)}" />`,
    `<meta property="og:url" content="${url}" />`,
    `<meta property="og:image" content="${image}" />`,
    `<meta property="og:image:secure_url" content="${image}" />`,
    `<meta property="og:image:type" content="image/jpeg" />`,
    `<meta property="og:image:width" content="1200" />`,
    `<meta property="og:image:height" content="630" />`,
    `<meta property="og:image:alt" content="${esc(m.og.headline)} — ${site.name}" />`,
    ...(m.article
      ? [
          `<meta property="article:published_time" content="${m.article.published}T09:00:00+01:00" />`,
          `<meta property="article:modified_time" content="${m.article.modified}T09:00:00+01:00" />`,
          `<meta property="article:section" content="${esc(m.article.section)}" />`,
          `<meta property="article:author" content="${site.name}" />`,
          ...m.article.tags.map((t) => `<meta property="article:tag" content="${esc(t)}" />`),
        ]
      : []),
    // Twitter / X
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${esc(title)}" />`,
    `<meta name="twitter:description" content="${esc(m.description)}" />`,
    `<meta name="twitter:image" content="${image}" />`,
    `<meta name="twitter:image:alt" content="${esc(m.og.headline)} — ${site.name}" />`,
    m.preload
      ? `<link rel="preload" as="image" type="image/webp" fetchpriority="high" imagesrcset="${m.preload.widths.map((w) => `${asset(`images/${m.preload!.name}-${w}.webp`)} ${w}w`).join(', ')}" imagesizes="${m.preload.sizes}" />`
      : '',
    ...ld.map((o) => `<script type="application/ld+json">${JSON.stringify(o).replace(/</g, '\\u003c')}</script>`),
  ];
  return tags.filter(Boolean).join('\n    ');
}

/** Absolute URLs of the main images on a page, for the image sitemap. */
export function pageImages(m: PageMeta) {
  return [{ url: imgUrl(m.og.image), caption: m.imageAlt }];
}
